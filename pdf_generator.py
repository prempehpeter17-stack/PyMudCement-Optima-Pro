import io
from datetime import datetime
from typing import Dict, Any, List, Optional
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors
from reportlab.pdfgen import canvas
from reportlab.graphics.shapes import Drawing, Rect, Line, String

class NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))
      
        if self._pageNumber > 1:
            self.drawString(54, 750, "PYMUDCEMENT OPTIMA PRO — TECHNICAL COMPLIANCE REPORT")
            self.setStrokeColor(colors.HexColor("#CBD5E1"))
            self.setLineWidth(0.5)
            self.line(54, 742, 558, 742)
          
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(1)
        self.line(54, 45, 558, 45)
      
        self.drawString(54, 32, "Generated by: PyMudCement Optima Pro Engine")
        self.drawCentredString(306, 32, "CONFIDENTIAL — DRILLING ENGINEERING DIVISION")
        self.drawRightString(558, 32, f"Page {self._pageNumber} of {page_count}")
        self.restoreState()

def generate_hydraulics_pdf(
    results: Dict[str, Any],
    diagnostic_report: Dict[str, Any],
    executed_by: str = "PyMudCement Automated Engine",
    segments: Optional[List[Dict[str, Any]]] = None,
    pv: float = 20.0,
    yp: float = 15.0
) -> io.BytesIO:
    """Standardized API Wrapper for generating hydraulic PDF reports."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter, leftMargin=54, rightMargin=54, topMargin=54, bottomMargin=64)
    styles = getSampleStyleSheet()

    title_style = ParagraphStyle('CompTitle', fontName='Helvetica-Bold', fontSize=20, leading=24, textColor=colors.HexColor('#0F172A'))
    subtitle_style = ParagraphStyle('CompSub', fontName='Helvetica', fontSize=11, leading=15, textColor=colors.HexColor('#0052CC'))
    h1_style = ParagraphStyle('SectH1', fontName='Helvetica-Bold', fontSize=13, leading=16, textColor=colors.HexColor('#0F172A'), spaceBefore=12, spaceAfter=6)
    body_style = ParagraphStyle('SectBody', fontName='Helvetica', fontSize=9, leading=12, textColor=colors.HexColor('#334155'))

    elements = [
        Paragraph("PYMUDCEMENT OPTIMA PRO", title_style),
        Paragraph("Drilling Hydraulics & Telemetry Engineering Report", subtitle_style),
        Spacer(1, 10)
    ]

    ecd = results.get("equivalent_circulating_density_ecd_ppg", 0.0)
    spp = results.get("standpipe_pressure_spp_psi", 0.0)

    # Metadata Table
    meta_data = [
        [Paragraph("<b>Executed By:</b>", body_style), Paragraph(executed_by, body_style), Paragraph("<b>Date:</b>", body_style), Paragraph(datetime.now().strftime('%Y-%m-%d %H:%M'), body_style)],
        [Paragraph("<b>Total Depth:</b>", body_style), Paragraph(f"{results.get('total_depth_ft', 0.0)} ft", body_style), Paragraph("<b>Flow Rate:</b>", body_style), Paragraph(f"{results.get('flow_rate_gpm', 0.0)} GPM", body_style)],
    ]
    t_meta = Table(meta_data, colWidths=[110, 140, 110, 140])
    t_meta.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#F8FAFC')),
        ('BOX', (0,0), (-1,-1), 1, colors.HexColor('#E2E8F0')),
        ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor('#F1F5F9')),
        ('TOPPADDING', (0,0), (-1,-1), 4),
        ('BOTTOMPADDING', (0,0), (-1,-1), 4),
    ]))
    elements.extend([t_meta, Spacer(1, 12)])

    # Physics Results Table
    elements.append(Paragraph("Hydraulics Summary", h1_style))
    phys_data = [
        [Paragraph("<b>Parameter</b>", body_style), Paragraph("<b>Value</b>", body_style)],
        [Paragraph("Equivalent Circulating Density (ECD)", body_style), Paragraph(f"{ecd:.2f} ppg", body_style)],
        [Paragraph("Standpipe Pressure (SPP)", body_style), Paragraph(f"{spp:.1f} psi", body_style)],
        [Paragraph("Annular Pressure Loss", body_style), Paragraph(f"{results.get('total_annular_pressure_loss_psi', 0.0):.1f} psi", body_style)],
        [Paragraph("Pipe Pressure Loss", body_style), Paragraph(f"{results.get('total_pipe_pressure_loss_psi', 0.0):.1f} psi", body_style)],
    ]
    t_phys = Table(phys_data, colWidths=[300, 200])
    t_phys.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#0F172A')),
        ('TEXTCOLOR', (0,0), (-1,0), colors.white),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#CBD5E1')),
        ('TOPPADDING', (0,0), (-1,-1), 5),
        ('BOTTOMPADDING', (0,0), (-1,-1), 5),
    ]))
    elements.extend([t_phys, Spacer(1, 12)])

    # Diagnostic Table
    elements.append(Paragraph("AI Telemetry & Risk Assessment", h1_style))
    severity = diagnostic_report.get("severity", "GREEN")
    bg_color = "#DCFCE7" if severity == "GREEN" else ("#FEF3C7" if severity == "YELLOW" else "#FEE2E2")
   
    diag_data = [
        [Paragraph("<b>Severity</b>", body_style), Paragraph(f"<b>{severity}</b>", body_style)],
        [Paragraph("<b>Matched Hazard</b>", body_style), Paragraph(diagnostic_report.get("matched_hazard", "None"), body_style)],
        [Paragraph("<b>Diagnosis</b>", body_style), Paragraph(diagnostic_report.get("detailed_diagnosis", ""), body_style)]
    ]
    t_diag = Table(diag_data, colWidths=[120, 380])
    t_diag.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor(bg_color)),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#CBD5E1')),
        ('TOPPADDING', (0,0), (-1,-1), 5),
        ('BOTTOMPADDING', (0,0), (-1,-1), 5),
    ]))
    elements.append(t_diag)

    doc.build(elements, canvasmaker=NumberedCanvas)
    buffer.seek(0)
    return buffer